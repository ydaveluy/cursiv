// How many plain rules stand on the native stack from each rule down; zero for
// a rule that is not plain: one with a climb, one that calls a rule that is not
// plain, or one deeper than `kLlPlainDepth`. Computed without recursion.
std::vector<std::uint8_t> ll_plain_depths(const LlLowCfg& c) {
  std::vector<std::vector<std::uint16_t>> callers(c.nrules);
  std::vector<std::uint16_t> waits(c.nrules, 0), ready, nodes;
  for (std::uint16_t r = 0; r < c.nrules; ++r) {
    if (c.rules[r].climb == kNoRow && c.rules[r].body != kNoRow)
      nodes.push_back(c.rules[r].body);
    while (!nodes.empty()) {
      const LlNode& n = c.nodes[nodes.back()];
      nodes.pop_back();
      if (n.kind == LlShape::call) callers[n.sym].push_back(r), ++waits[r];
      for (const auto k : c.children(n)) nodes.push_back(k);
    }
    if (waits[r] == 0) ready.push_back(r);
  }
  // A rule that is not plain weighs as one at the limit.
  std::vector<std::uint8_t> depth(c.nrules, 0), below(c.nrules, 0);
  while (!ready.empty()) {
    const std::uint16_t r = ready.back();
    ready.pop_back();
    if (c.rules[r].climb == kNoRow && below[r] < kLlPlainDepth)
      depth[r] = below[r] + 1;
    for (const auto p : callers[r]) {
      below[p] = std::max(below[p], depth[r] == 0 ? kLlPlainDepth : depth[r]);
      if (--waits[p] == 0) ready.push_back(p);
    }
  }
  return depth;
}

std::string ll_emit_parser_decl(const std::string& ns) {
  std::string s(kGenerated);
  s += "#pragma once\n\n";
  s += "namespace cursiv::engine {\nstruct LlContext;\n}  // namespace "
       "cursiv::engine\n\n";
  s += concat("namespace ", ns, " {\n");
  s += "void parse_entry(::cursiv::engine::LlContext&);\n";
  s += "inline constexpr void (*kDrive)(::cursiv::engine::LlContext&) = "
       "&parse_entry;\n";
  s += concat("}  // namespace ", ns, "\n");
  return s;
}

std::vector<std::pair<std::string, std::string>> ll_emit_parser_files(
    const LlFinalProgram& done, const std::string& ns,
    const LlTableSource& table) {
  const Built& a = done.program();
  const LlStampPlan& plan = done.plan();
  bool levels = false;
  for (std::uint16_t t = 1; t < a.cfg.nterms; ++t)
    levels = levels || a.cfg.terms[t].synthetic == kSyntheticIndent ||
             a.cfg.terms[t].synthetic == kSyntheticDedent;
  Memos memo{.plain = ll_plain_depths(a.cfg), .steps = a.cfg.nrules};
  std::string declarations = concat("\nnamespace ", ns, " {\n");
  std::vector<std::string> bodies;
  std::size_t bytes = 0;
  // The machine steps the rules that resume: a plain rule, the entry
  // included, is only ever called in place. The arms that are steps follow the
  // rules, in the order of their numbers.
  std::vector<bool> stepped(a.cfg.nrules, false);
  std::string armSteps;
  std::string armSizes;
  // Each rule and arm is declared as a function, or as a step with its frame;
  // a step also takes the machine's case for its number and its frame's size.
  const auto declare = [&](std::string_view tag, const std::string& frame) {
    declarations +=
        frame.empty()
            ? concat("void s", tag, "(::cursiv::engine::LlContext&);\n")
            : concat(frame, "::std::uint16_t s", tag,
                     "(::cursiv::engine::LlContext&, void*);\n");
  };
  const auto step = [](std::string& steps, std::string& sizes,
                       std::uint32_t number, std::string_view tag) {
    steps += concat("    case ", number, "u: return s", tag, "(c, f);\n");
    sizes += concat("sizeof(F", tag, "), ");
  };
  for (std::uint16_t r = 1; r < a.cfg.nrules; ++r)
    if (a.liveRules[r]) {
      Emit e{TextBuilder(kLayout), a, plan, memo};
      e.levels = levels;
      e.rule(r);
      stepped[r] = !e.frame.empty();
      declare(std::to_string(r), e.frame);
      bytes += e.size();
      bodies.push_back(e.take());
      for (Emit::Arm& arm : e.arms) {
        declare(arm.tag, arm.frame);
        if (!arm.frame.empty()) step(armSteps, armSizes, arm.step, arm.tag);
        bytes += arm.body.size();
        bodies.push_back(std::move(arm.body));
      }
    }
  declarations += concat("}  // namespace ", ns, "\n");
  std::string steps, sizes;
  for (std::uint16_t r = 0; r < a.cfg.nrules; ++r)
    if (stepped[r])
      step(steps, sizes, r, std::to_string(r));
    else
      sizes += "0u, ";
  steps += armSteps;
  sizes += armSizes;
  // A plain entry reaches only plain rules, which never resume: no machine.
  const std::uint16_t entry = a.cfg.entryRule;
  const std::string drive =
      stepped[entry]
          ? concat(
                "namespace {\n"
                "::std::uint16_t step(::std::uint16_t r, "
                "::cursiv::engine::LlContext& c, "
                "[[maybe_unused]] void* f) {\n  switch (r) {\n",
                steps,
                "    default: return ::cursiv::engine::kLlDone;\n  }\n}\n"
                "constexpr ::std::uint32_t kFrameBytes[] = {",
                sizes,
                "};\n"
                "}  // namespace\n"
                "void parse_entry(::cursiv::engine::LlContext& c) {\n"
                "  c.stack.reserve(64);\n"
                "  ::cursiv::engine::LlMachine machine;\n"
                "  machine.run<&step>(c, ",
                entry, "u, kFrameBytes);\n}\n")
          : concat(
                "void parse_entry(::cursiv::engine::LlContext& c) {\n"
                "  c.stack.reserve(64);\n  s",
                entry, "(c);\n}\n");
  // A bounded set of translation units keeps the optimizer from repeatedly
  // opening an entire language. The frames are declared once, so the
  // machine's unit sizes every one of them.
  const std::size_t budget =
      std::max<std::size_t>(32768, (bytes + kParserUnits - 1) / kParserUnits);
  std::vector<std::string> sources(kParserUnits, std::string(kGenerated));
  std::size_t next = 0;
  unsigned filled = 0;
  for (unsigned u = 0; u < kParserUnits && next < bodies.size();
       ++u, ++filled) {
    std::string& source = sources[u];
    source +=
        "#include <cstdint>\n#include <new>\n\n#include \"ParserRules.hpp\"\n"
        "#include \"Table.hpp\"\n"
        "#include \"cursiv/ll/runtime/LlMachine.hpp\"\n"
        "#include \"cursiv/ll/runtime/ll_predictor.hpp\"\n"
        "#include \"cursiv/ll/runtime/ll_repair.hpp\"\n";
    if (a.cfg.ngapConds != 0)
      source += "#include \"cursiv/ll/runtime/ll_conditions.hpp\"\n";
    source += concat("\nnamespace ", ns, " {\n\n");
    std::size_t used = 0;
    do {
      used += bodies[next].size();
      source += bodies[next++];
    } while (next < bodies.size() && (used < budget || u + 1 == kParserUnits));
    source += concat("}  // namespace ", ns, "\n");
  }
  // Rules spread over several units share their cold paths: every unit
  // declares them, and the parser's own unit compiles them, once. The rules of
  // a single unit keep them, where the optimizer of the descent sees them.
  const bool shared = filled > 1;
  const auto cold = [&](std::string_view how) {
    std::string s = "\n";
    for (const auto& [paths, wanted] :
         {std::pair{"", true}, std::pair{"PREDICT_", memo.predicts},
          std::pair{"CONDITION_", a.cfg.ngapConds != 0},
          std::pair{"PREDICT_CONDITION_",
                    memo.predicts && a.cfg.ngapConds != 0},
          std::pair{"CLIMB_", a.cfg.nclimbs != 0}})
      if (wanted)
        s += concat("CURSIV_LL_", paths, "COLD_PATHS(", how, ", ::", ns,
                    "::kTable);\n");
    return s;
  };
  std::string header =
      concat(kGenerated,
             "#pragma once\n\n#include <cstdint>\n\n#include \"Parser.hpp\"\n"
             "#include \"cursiv/syntax-tree/CstBuilder.hpp\"\n"
             "#include \"cursiv/ll/runtime/LlSection.hpp\"\n");
  if (levels)
    header += "#include \"cursiv/shared/runtime/IndentLevel.hpp\"\n";
  if (shared)
    header +=
        "#include \"Table.hpp\"\n"
        "#include \"cursiv/ll/runtime/ll_cold.hpp\"\n";
  header += declarations;
  if (shared) header += cold("extern");
  std::vector<std::pair<std::string, std::string>> files;
  files.emplace_back("ParserRules.hpp", std::move(header));
  files.emplace_back(
      "ParserStates.cpp",
      concat(kGenerated,
             "#include <cstdint>\n\n#include \"ParserRules.hpp\"\n"
             "#include \"cursiv/ll/runtime/LlContext.hpp\"\n"
             "#include \"cursiv/ll/runtime/LlMachine.hpp\"\n",
             ll_emit_walk_includes(a), table.includes,
             "\n"
             "namespace ",
             ns, " {\n\n", table.functions, ll_emit_walk(a), "\n", drive,
             "}  // namespace ", ns, "\n", shared ? cold("") : std::string{}));
  for (unsigned u = 0; u < kParserUnits; ++u)
    files.emplace_back(concat("ParserRules", u, ".cpp"), std::move(sources[u]));
  return files;
}

