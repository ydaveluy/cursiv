constexpr std::string_view kGenerated =
    "// GENERATED by the predictive engine -- do not edit.\n";

// Where a record opened: the names of the tape cursor, the text offset and the
// record count taken there. Empty while none stands.
struct Anchor {
  std::string open{}, begin{}, count{};
  bool live() const { return !count.empty(); }
};

// A slot holds `value` for a scope and gives back what it held; with no
// value it only gives back what the scope leaves in it.
class Anchored {
 public:
  explicit Anchored(Anchor& slot) : _slot(slot), _outer(slot) {}
  Anchored(Anchor& slot, Anchor value) : _slot(slot), _outer(std::move(slot)) {
    _slot = std::move(value);
  }
  ~Anchored() { _slot = std::move(_outer); }
  Anchored(const Anchored&) = delete;
  Anchored& operator=(const Anchored&) = delete;

 private:
  Anchor& _slot;
  Anchor _outer;
};

// Shared by every rule's emitter: which rules are plain, whether a position may
// suspend, and the first mode it reads. A search marks the rules it visits with
// a round number, so it needs no clearing.
struct Memos {
  std::vector<std::uint8_t> plain{};
  std::vector<std::int8_t> suspends{};
  std::vector<std::int8_t> clean{};
  std::vector<std::uint32_t> visited{};
  std::uint32_t round = 0;
  // The machine's number for the next arm that is a step: the rules hold the
  // numbers below the first.
  std::uint32_t steps = 0;
  // Whether a step asks the prediction: its cold paths are compiled then.
  bool predicts = false;
};

// Past this depth a block deepens the code and not its indentation, whose bytes
// would grow with the square of a nest's depth.
constexpr TextBuilder::Options kLayout{.step = 2, .maxIndent = 48};

struct Emit : TextBuilder {
  const Built& a;
  const LlStampPlan& plan;
  Memos& memo;
  std::uint16_t inRule = 0;
  unsigned uniq = 0;
  // A level opens or closes in no byte: a turn moves the cursor or a level.
  bool levels = false;
  Anchor foldAt{};
  // The record a nest turn reaches back to: the sequence it stands in, with
  // the tape length where that sequence opened. A group whose position is
  // such a sequence passes its own opening on.
  Anchor regionAt{};
  std::uint16_t ownRegion = kNoRow;
  Anchor ownAt{};
  // The body of a fold step: past its first reading, a nest wraps what the
  // fold has read.
  bool inStep = false;
  // What outlives a call goes in the rule's frame; the calls are numbered by
  // the label each resumes at.
  std::vector<std::pair<std::string, std::string>> fields{};
  // The fields the open scopes hold, and the ones closed scopes gave back. A
  // field is named only inside the scope that took it, so a later scope may
  // take it again: positions that are never live at once share frame bytes.
  std::vector<std::size_t> inUse{}, spare{};
  unsigned resumes = 0;
  // Each field as it is taken and each label the step resumes at, in the
  // order the code names them: an arm that becomes a step of its own takes
  // the ones named while it was written into its own frame.
  std::vector<std::size_t> taken{};
  std::vector<unsigned> labels{};
  // A counted tail of nest turns is written one turn inside the other, a block
  // deeper each: past this many the source exceeds the nesting a compiler
  // must accept, and the emitter's walk exceeds its stack.
  static constexpr unsigned kMaxNestedTurns = 64;
  unsigned nestedTurns = 0;
  bool exits = false;
  std::string frame{};
  // An arm emitted on its own, `s<tag>`: a function, or where it may suspend a
  // step with its frame `F<tag>` and its number on the machine.
  struct Arm {
    std::string tag{};
    std::string frame{};
    std::string body{};
    std::uint32_t step = kNoRow;
  };
  std::vector<Arm> arms{};
  // Past this many bytes of source an arm that can stand alone is a function
  // or a step: a rule's step stays a size the compiler handles well, and the
  // units share the arms of one large rule.
  static constexpr std::size_t kArmBytes = 16384;
  // The machine numbers its steps below its `kLlDone`.
  static constexpr std::uint32_t kLastStep = 0xFFFFu;

  void over_fold() {
    if (foldAt.live()) regionAt = foldAt;
  }

  // A spare field of the type if one is left, a new one otherwise.
  std::string field(std::string_view type, std::string_view stem) {
    for (std::size_t k = spare.size(); k-- > 0;)
      if (fields[spare[k]].first == type) {
        inUse.push_back(spare[k]);
        spare.erase(spare.begin() + static_cast<std::ptrdiff_t>(k));
        taken.push_back(inUse.back());
        return "f." + fields[inUse.back()].second;
      }
    inUse.push_back(fields.size());
    return "f." + frame_field(type, name(stem));
  }
  // A field that is never given back.
  const std::string& frame_field(std::string_view type, std::string name) {
    taken.push_back(fields.size());
    return fields.emplace_back(std::string(type), std::move(name)).second;
  }
  // The frame `F<tag>` of the fields taken from `from` on, the switch that
  // jumps to the labels named from `resumed` on, and the head of step `s<tag>`
  // that opens its frame and that switch.
  std::string frame_of(std::string_view tag, std::size_t from) const;
  std::string resume_switch(std::size_t resumed) const;
  std::string step_head(std::string_view tag, std::size_t resumed) const;
  // The label the next call resumes at. The frame names it in sixteen bits:
  // a rule whose labels outrun them is refused.
  unsigned next_label() {
    if (resumes == 0xFFFFu)
      refuse_lowering(
          std::format("rule `{}` {}", a.cfg.rule_name(inRule),
                      lower_fail_text(LowerFail::tooManyPositions)));
    labels.push_back(++resumes);
    return resumes;
  }
  // A field where the scope may suspend, a local otherwise.
  std::string local(bool held, std::string_view type, std::string_view stem) {
    return held ? field(type, stem) : name(stem);
  }

  // Open while one position's code is written: the fields taken meanwhile go
  // back to the pool when it closes.
  class FieldScope {
   public:
    explicit FieldScope(Emit& e) : _e(e), _mark(e.inUse.size()) {}
    ~FieldScope() {
      for (std::size_t k = _mark; k < _e.inUse.size(); ++k)
        _e.spare.push_back(_e.inUse[k]);
      _e.inUse.resize(_mark);
    }
    FieldScope(const FieldScope&) = delete;
    FieldScope& operator=(const FieldScope&) = delete;

   private:
    Emit& _e;
    std::size_t _mark;
  };

  std::string name(std::string_view stem) { return concat(stem, uniq++); }

  const LlNode& at(std::uint16_t id) const { return a.cfg.nodes[id]; }
  std::uint16_t child_at(const LlNode& n, unsigned i) const {
    return a.cfg.childIds[n.sym + i];
  }

  Descent<std::uint16_t> first_mode(std::uint16_t id) const;
  Descent<std::uint16_t> rule_mode(std::uint16_t r) const;
  void new_search() const {
    if (memo.visited.size() != a.cfg.nrules)
      memo.visited.assign(a.cfg.nrules, 0);
    ++memo.round;
  }
  std::uint16_t mode_of(std::uint16_t id) const {
    new_search();
    const std::uint16_t m = descend(first_mode(id));
    return m == kNoRow ? a.errMode : m;
  }

  // A token already read, and what its point proved about it: `kNoRow` for
  // none, `kAnyToken` for one the switch did not pin down. The descent reads
  // once per point.
  static constexpr std::uint16_t kAnyToken = 0xFFFEu;
  Descent<void> node(std::uint16_t id, std::uint16_t hand = kNoRow);
  void leaf(std::uint16_t id, std::uint16_t hand, std::uint16_t row);
  Descent<void> group(std::uint16_t id, std::uint16_t hand = kNoRow);
  Descent<void> decision(std::uint16_t id);
  void peek_choice(std::uint16_t d, std::string_view mode, bool constant);
  Descent<void> arm(std::uint16_t id, std::uint16_t hand);
  bool word_rule(std::uint16_t r) const;
  void term_choice(std::uint16_t id,
                   const std::vector<std::vector<std::uint16_t>>& byArm);
  Descent<void> sequence(std::uint16_t id, std::uint16_t hand);
  Descent<void> repetition(std::uint16_t id, std::uint16_t body = kNoRow);
  bool counted_tail_flat(std::uint16_t id) const;
  Descent<void> counted_tail(std::uint16_t id);
  void call_site(std::uint16_t id);
  Descent<bool> may_suspend(std::uint16_t id);
  bool turns(std::uint16_t id) const { return plan.turns(id); }
  bool reaches_back(std::uint16_t id) const {
    return plan.reaches_back(id);
  }
  // A rule that opens no frame and never resumes.
  bool plain(std::uint16_t r) const { return memo.plain[r] != 0; }
  Descent<bool> clean(std::uint16_t id);
  bool finishes(std::uint16_t r);
  void invoke(std::uint16_t callee, std::string_view arg);
  void climb(std::uint16_t r);
  void rule(std::uint16_t r);
  void join(std::uint32_t base, std::uint32_t count, std::string_view from);
};

Descent<std::uint16_t> Emit::rule_mode(std::uint16_t r) const {
  if (r >= a.cfg.nrules || memo.visited[r] == memo.round) co_return kNoRow;
  memo.visited[r] = memo.round;
  const LlRuleInfo& u = a.cfg.rules[r];
  if (u.climb != kNoRow)
    co_return co_await rule_mode(a.cfg.climbs[u.climb].primary);
  if (u.body == kNoRow) co_return kNoRow;
  co_return co_await first_mode(u.body);
}

// The alphabet the first token of this position is read with: a record opened
// over the position begins where that token does, so the peek comes first and
// the trivia in front of it stays outside.
Descent<std::uint16_t> Emit::first_mode(std::uint16_t id) const {
  const LlNode& n = at(id);
  switch (n.kind) {
    case LlShape::term:
    case LlShape::endMark:
    case LlShape::condition:
    case LlShape::implied:
      co_return n.mode;
    case LlShape::call:
      if (n.mode != kNoRow) co_return n.mode;
      co_return co_await rule_mode(n.sym);
    case LlShape::alt:
      co_return a.cfg.decisions[n.decision].mode;
    case LlShape::rep:
      // Opening a record must not commit the caller trivia a nullable
      // repetition only inspects while deciding whether to take an item.
      co_return a.callerPeek[id] ? a.readHeadMode[n.decision]
                                 : a.headMode[n.decision];
    case LlShape::seq: {
      for (unsigned i = 0; i < n.count; ++i) {
        const std::uint16_t m = co_await first_mode(child_at(n, i));
        if (m != kNoRow) co_return m;
      }
      co_return kNoRow;
    }
    default:
      co_return kNoRow;
  }
}

void Emit::join(std::uint32_t base, std::uint32_t count,
                std::string_view from) {
  if (!ll_fuse_tabled(count, false)) {
    if (count == 1)
      line("::cursiv::engine::ll_join_one<kTable>(c, ", from, ", ",
           a.fuse[base].to, "u);");
    return;
  }
  line("::cursiv::engine::ll_join<kTable>(c, ", from, ", kFuse + ", base, "u, ",
       count, "u);");
}

// A rule that reads one terminal whichever way it goes, each on a token of its
// own, and states the same over each: its site can read it as a terminal.
bool Emit::word_rule(std::uint16_t r) const {
  const LlRuleInfo& u = a.cfg.rules[r];
  if (u.body == kNoRow || u.climb != kNoRow) return false;
  const LlNode& n = at(u.body);
  if (n.kind != LlShape::alt || n.owns || n.row != kNoRow) return false;
  const LlDecision& dec = a.cfg.decisions[n.decision];
  if ((a.cfg.ngapConds != 0 && dec.how != LlPredict::single) ||
      a.modeMulti[dec.mode] == 1 || a.decEnded[n.decision] != 0 ||
      a.decFlag[n.decision].any() || a.decStands[n.decision] != 0)
    return false;
  for (std::uint16_t i = 0; i < dec.nalts; ++i) {
    const LlNode& x = at(child_at(n, i));
    if (x.kind != LlShape::term || x.owns || x.row != at(child_at(n, 0)).row)
      return false;
    const DynSet& reads = a.laSet[dec.set + i];
    if (!reads.test(x.sym) || reads.more_than_one()) return false;
  }
  return true;
}

void Emit::call_site(std::uint16_t id) {
  const FieldScope scope(*this);
  const LlNode& n = at(id);
  if (n.mode != kNoRow)
    line("::cursiv::engine::ll_peek<kTable, ", n.mode, "u>(c);");
  // A nullable callee may inspect its exit under another trivia setting.
  // Commit only the actual entry gap before handing that decision over.
  if (a.callerPeek[id]) line("::cursiv::engine::ll_flush_trivia<kTable>(c);");
  const std::uint32_t base = a.fuseBase[id];
  const std::uint32_t count = a.fuseBase[id + 1] - base;
  // A section reads its grammar alone, and what its entry left is dropped
  // up to the token that closes it.
  const std::uint8_t section = n.section;
  // What the site keeps across a plain callee ends with it, as a group's
  // locals do.
  const bool held = descend(may_suspend(id));
  // The token in place, as a terminal is read: the rule is called only for a
  // repair, where the token is none of its own.
  const bool word = !held && section == 0 && count <= 1 && !a.callerPeek[id] &&
                    word_rule(n.sym);
  if (word) {
    const LlNode& body = at(a.cfg.rules[n.sym].body);
    const std::string pos = name("p");
    line("::std::uint16_t ", pos, ";");
    line(pos, " = 0u;");
    open("if (!c.give) {");
    peek_choice(body.decision, concat(a.cfg.decisions[body.decision].mode, "u"),
                true);
    open("switch (c.la.sym) {");
    for (std::uint16_t i = 0; i < a.cfg.decisions[body.decision].nalts; ++i)
      line("case ", at(child_at(body, i)).sym, "u: ", pos, " = ",
           child_at(body, i) + 1, "u; break;");
    line("default: break;");
    close("}");
    close("}");
    line("if (", pos,
         " != 0u) [[likely]] ::cursiv::engine::ll_consume<kTable>(c, ",
         count == 1 ? a.fuse[base].to : at(child_at(body, 0)).row, "u, ", pos,
         ");");
    open("else {");
  }
  const bool scoped = !held && (count != 0 || section != 0);
  if (scoped) open("{");
  const std::string was =
      count == 0 ? std::string{} : local(held, "::cursiv::NodeId", "w");
  if (count != 0)
    line(held ? "" : "const ::cursiv::NodeId ", was, " = c.last;");
  std::string outer;
  if (section != 0) {
    outer = local(held, "::cursiv::engine::LlSection", "sec");
    line(held ? "" : "const ::cursiv::engine::LlSection ", outer,
         " = ::cursiv::engine::ll_section_open<kTable>(c, ", section, "u);");
  }
  line("c.stack.push_back(", a.nodeAfter[id],
       "u, c.tape.stream().records());");
  invoke(n.sym, "1u");
  line("::cursiv::engine::ll_return(c);");
  if (section != 0)
    line("::cursiv::engine::ll_section_close<kTable>(c, ", outer, ");");
  join(base, count, was);
  if (scoped) close("}");
  if (word) close("}");
}

// Whether a position calls, anywhere inside, a rule that is not plain: the
// call may leave the step to resume at a label, so a record open across it
// keeps its handles in the frame.
Descent<bool> Emit::may_suspend(std::uint16_t id) {
  if (memo.suspends.empty()) memo.suspends.assign(a.cfg.nnodes, -1);
  if (memo.suspends[id] >= 0) co_return memo.suspends[id] != 0;
  const LlNode& n = at(id);
  bool any = n.kind == LlShape::call && !plain(n.sym);
  if (n.kind == LlShape::seq || n.kind == LlShape::alt)
    for (unsigned i = 0; i < n.count; ++i)
      any = co_await may_suspend(child_at(n, i)) || any;
  if (n.kind == LlShape::rep) {
    // A tail of counted options is walked, never descended: it may be as
    // deep as the count.
    std::uint16_t turn = id;
    while (at(turn).countedTail && at(at(turn).sym).countedTail) {
      any = co_await may_suspend(child_at(at(at(turn).sym), 0)) || any;
      turn = child_at(at(at(turn).sym), 1);
    }
    any = co_await may_suspend(at(turn).sym) || any;
  }
  memo.suspends[id] = any ? 1 : 0;
  co_return any;
}

// Whether a position has a reading that calls no rule with a frame.
Descent<bool> Emit::clean(std::uint16_t id) {
  if (memo.clean.empty()) memo.clean.assign(a.cfg.nnodes, -1);
  if (memo.clean[id] >= 0) co_return memo.clean[id] != 0;
  const LlNode& n = at(id);
  bool any = true;
  if (n.kind == LlShape::call) any = plain(n.sym);
  if (n.kind == LlShape::seq)
    for (unsigned i = 0; i < n.count && any; ++i)
      any = co_await clean(child_at(n, i));
  if (n.kind == LlShape::alt) {
    any = false;
    for (unsigned i = 0; i < n.count && !any; ++i)
      any = co_await clean(child_at(n, i));
  }
  if (n.kind == LlShape::rep && n.min != 0) any = co_await clean(n.sym);
  memo.clean[id] = any ? 1 : 0;
  co_return any;
}

// Whether a rule can finish where its caller runs it: a reading of it calls no
// rule that would hand its frame over. A climb calls its primary first.
bool Emit::finishes(std::uint16_t r) {
  const LlRuleInfo& u = a.cfg.rules[r];
  if (u.climb != kNoRow) return plain(a.cfg.climbs[u.climb].primary);
  return u.body == kNoRow || descend(clean(u.body));
}

// A callee that can finish in place runs there; any other returns the call to
// the machine, which runs it and comes back to the label. A local read across
// the label is a frame field. A plain callee is a plain call.
void Emit::invoke(std::uint16_t callee, std::string_view arg) {
  if (plain(callee)) {
    line("s", callee, "(c);");
    return;
  }
  const unsigned k = next_label();
  if (a.cfg.rules[callee].climb != kNoRow) line("c.arg = ", arg, ";");
  line("f.pc = ", k, "u;");
  if (finishes(callee)) {
    line(
        "if (const ::std::uint16_t next = "
        "::cursiv::engine::ll_call<F",
        callee, ", &s", callee, ">(c, ", callee, "u);");
    line("    next != ::cursiv::engine::kLlDone)");
    line("  return next;");
  } else {
    line("return ", callee, "u;");
  }
  line("L", k, ":;");
}

// A group that owns a record: the token in front of it is read first, so the
// trivia that precedes it stays outside and the record begins where the text
// does.
Descent<void> Emit::group(std::uint16_t id, std::uint16_t hand) {
  const FieldScope scope(*this);
  const LlNode& n = at(id);
  // An empty position has no token to wait for: it creates its own record.
  if (!n.owns || n.kind == LlShape::empty) {
    co_await node(id, hand);
    co_return;
  }
  const bool held = co_await may_suspend(id);
  const bool checkpoint = n.kind == LlShape::seq && n.count == 0 && turns(id);
  const std::uint32_t ob = a.ownBase[id];
  const std::uint32_t oc = a.ownBase[id + 1] - ob;
  const bool step = n.foldStep;
  if (step && foldAt.open.empty())
    throw std::logic_error("cursiv: LL fold step has no prefix region");
  // A nest turn's record begins at its receiver, its first child; its
  // position says it has one.
  const bool turn = turns(id) && regionAt.live();
  // With no receiver to wrap, the nest goes onto its lone terminal.
  if (turns(id) && !turn && n.leafRow != kNoRow) {
    leaf(child_at(n, 0), hand, n.leafRow);
    co_return;
  }
  const bool region = !turns(id) && reaches_back(id);
  const bool folds =
      n.kind == LlShape::seq && n.count == 2 && at(child_at(n, 1)).leftFold;
  const bool counted = oc != 0 || region || folds;
  const std::string o = local(held, "::cursiv::CstBuilder::Open", "o");
  const std::string b = local(held, "::cursiv::TextOffset", "b");
  const std::string f = local(held && counted, "::cursiv::NodeCount", "f");
  const std::string l =
      !turn ? std::string("0") : local(held, "::std::uint16_t", "l");
  if (!checkpoint) {
    if (hand == kNoRow)
      line("::cursiv::engine::ll_peek<kTable, ", mode_of(id), "u>(c);");
    line("::cursiv::engine::ll_flush_trivia<kTable>(c);");
  }
  // Its locals end with it: a label further on in the block may not cross
  // their initialisation.
  if (!held) open("{");
  if (turn) {
    line(held ? "" : "const ::std::uint16_t ", l,
         " = ::cursiv::engine::ll_nest_receiver<kTable>(c, ", regionAt.open,
         ", ", regionAt.begin, ", ", regionAt.count, ");");
    line(held ? "" : "const auto ", o, " = ", l, " != 0 ? ", regionAt.open,
         " : c.tape.enter();");
    if (counted)
      line(held ? "" : "const ::cursiv::NodeCount ", f, " = ", l, " != 0 ? ",
           regionAt.count, " : c.tape.stream().records();");
    line(held ? "" : "const ::cursiv::TextOffset ", b, " = ", l, " != 0 ? ",
         regionAt.begin, " : ",
         checkpoint ? "::std::max(c.at, c.triviaAt)" : "c.la.begin", ";");
  } else {
    line(held ? "" : "const auto ", o, " = ",
         step ? foldAt.open : "c.tape.enter()", ";");
    // The tape's length is kept only where a reused subtree or a turn may read
    // it back.
    if (counted)
      line(held ? "" : "[[maybe_unused]] const ::cursiv::NodeCount ", f,
           " = c.tape.stream().records();");
    line(held ? "" : "const ::cursiv::TextOffset ", b, " = ",
         step         ? foldAt.begin
         : checkpoint ? "::std::max(c.at, c.triviaAt)"
                      : "c.la.begin",
         ";");
  }
  const Anchor here{o, b, f};
  const Anchored foldHere = folds ? Anchored(foldAt, here) : Anchored(foldAt);
  // A creation isolates its prefix; an adopting close keeps the current
  // construction available to any later checkpoint in the same context.
  if (region) {
    ownRegion = id;
    ownAt = here;
  }
  const Anchored regionHere(
      regionAt, a.writes.chainBuild[n.row].creates ? Anchor{} : regionAt);
  const bool outerStep = inStep;
  inStep = step;
  co_await node(id, hand);
  inStep = outerStep;
  // The hand-over ends with the group, whose fields go back to the pool.
  if (region) {
    ownRegion = kNoRow;
    ownAt = {};
  }
  // A record that opens no node states over one its body builds.
  const std::string closer = a.writes.chainBuild[n.row].creates
                                 ? "::cursiv::engine::ll_close<kTable>("
                                 : "::cursiv::engine::ll_close_over<kTable>(";
  if (!ll_fuse_tabled(oc, true)) {
    line("c.last = ", closer, "c, ", o, ", ", b, ", kTable.stamp.make(", n.row,
         "u, ",
         plan.stamps(id) ? std::to_string(LlStampPlan::state(inRule)) : l,
         "));");
  } else {
    // A turn that reached back covers more than one subtree: no reused subtree
    // there.
    if (turn)
      line("if (", l,
           " != 0 || !::cursiv::engine::ll_reuse_subtree<kTable>(c, ", f,
           ", kFuse + ", ob, "u, ", oc, "u))");
    else
      line("if (!::cursiv::engine::ll_reuse_subtree<kTable>(c, ", f,
           ", kFuse + ", ob, "u, ", oc, "u))");
    open();
    line("c.last = ", closer, "c, ", o, ", ", b, ", kTable.stamp.make(", n.row,
         "u, ", l, "));");
    close();
  }
  if (!held) close("}");
}

// Every transparent position shares its construction prefix. A creation
// opens a new one; a nest checkpoints it without hiding it from later nests.
Descent<void> Emit::sequence(std::uint16_t id, std::uint16_t hand) {
  const FieldScope scope(*this);
  const LlNode& n = at(id);
  const bool region = reaches_back(id);
  // A fold that owns no record anchors its steps where its base begins.
  const bool folds = !n.owns && n.count == 2 && at(child_at(n, 1)).leftFold;
  const Anchor outer = regionAt;
  const bool over = inStep && !outer.live() && foldAt.live();
  const Anchor& reach = over ? foldAt : outer;
  Anchor start;
  bool scoped = false;
  if (region && reach.live()) {
    start = reach;
  } else if (region && ownRegion == id) {
    start = ownAt;
  } else if (region || folds) {
    const bool held = co_await may_suspend(id);
    if (hand == kNoRow)
      line("::cursiv::engine::ll_peek<kTable, ", mode_of(id), "u>(c);");
    line("::cursiv::engine::ll_flush_trivia<kTable>(c);");
    if (!held) {
      open("{");
      scoped = true;
    }
    start.open = local(held, "::cursiv::CstBuilder::Open", "o");
    start.begin = local(held, "::cursiv::TextOffset", "b");
    start.count = local(held, "::cursiv::NodeCount", "f");
    const std::string decl =
        held ? "" : region ? "[[maybe_unused]] const " : "const ";
    line(decl, held ? "" : "auto ", start.open, " = c.tape.enter();");
    line(held ? "" : "[[maybe_unused]] const ::cursiv::NodeCount ", start.count,
         " = c.tape.stream().records();");
    line(decl, held ? "" : "::cursiv::TextOffset ", start.begin,
         " = c.la.begin;");
  }
  const Anchored foldHere = folds ? Anchored(foldAt, start) : Anchored(foldAt);
  const Anchored regionHere(regionAt);
  for (unsigned k = 0; k < n.count; ++k) {
    const std::uint16_t x = child_at(n, k);
    regionAt = start.live() ? start : reach;
    co_await group(x, k == 0 ? hand : kNoRow);
  }
  if (scoped) close("}");
}

// The token choice `d` reads under `mode`, a constant or an expression. A
// terminal only a caller admits that reads over another is asked of the frames
// first.
void Emit::peek_choice(std::uint16_t d, std::string_view mode, bool constant) {
  if (constant)
    line("::cursiv::engine::ll_peek<kTable, ", mode, ">(c);");
  else
    line("::cursiv::engine::ll_peek<kTable>(c, ", mode, ");");
  if (a.decFlag[d].any())
    line("if (kTable.holds(kTable.dec_flag(", d,
         "u), c.la.sym)) [[unlikely]] "
         "::cursiv::engine::ll_refuse_flagged<kTable>(c, ",
         mode, ", ", d, "u);");
  if (a.decStands[d] != 0) line("::cursiv::engine::ll_hold<kTable>(c);");
}

// The arms of a choice, and the token that picks one. What one token decides
// is a case; the rest asks the prediction, only for the tokens that leave more
// than one arm.
Descent<void> Emit::decision(std::uint16_t id) {
  const LlNode& n = at(id);
  const LlDecision& dec = a.cfg.decisions[n.decision];
  // Which arms one token admits: an arm alone on a token is a case of its own.
  std::vector<std::vector<std::uint16_t>> armOf(a.cfg.nterms);
  for (std::uint16_t i = 0; i < dec.nalts; ++i)
    for (const unsigned t : a.laSet[dec.set + i].members())
      armOf[t].push_back(i);
  std::vector<std::vector<std::uint16_t>> byArm(dec.nalts);
  bool shared = false;
  for (std::uint16_t t = 0; t < a.cfg.nterms; ++t) {
    if (armOf[t].size() == 1)
      byArm[armOf[t][0]].push_back(t);
    else if (armOf[t].size() > 1)
      shared = true;
  }
  // A token alone cannot establish a predicate on the gap before it.
  if ((a.cfg.ngapConds != 0 && dec.how != LlPredict::single) ||
      a.modeMulti[dec.mode] == 1) {
    shared = true;
    for (auto& arm : byArm) arm.clear();
  }
  // Where the text ends on the token, the prediction reads what else it may
  // be: the token decides the arm everywhere else.
  const bool ended = a.decEnded[n.decision] != 0;
  if (ended) shared = true;
  // A token no arm admits after the skip. The prediction is not asked: with no
  // reading it answers the first arm, which in a recursive rule invents its way
  // down.
  const bool asks =
      (dec.how != LlPredict::single || ended) && shared && dec.repairCost <= 1;
  const bool direct = !ended && (dec.how == LlPredict::single || !shared);
  // Arms that each read one terminal and nothing else, each on a token of
  // its own.
  bool terms = direct;
  for (std::uint16_t i = 0; i < dec.nalts && terms; ++i) {
    const LlNode& x = at(child_at(n, i));
    terms = x.kind == LlShape::term && !x.owns && byArm[i].size() == 1 &&
            byArm[i][0] == x.sym;
  }
  if (terms) {
    term_choice(id, byArm);
    co_return;
  }
  const std::string none = name("none");
  const std::string k = name("k");
  peek_choice(n.decision, concat(dec.mode, "u"), true);
  if (asks) {
    line("bool ", none, ";");
    line(none, " = false;");
  }
  if (!direct) {
    line("::std::uint16_t ", k, ";");
    line(k, " = 0xFFFFu;");
  }
  // A token no arm takes: the repair names the arm it enters, inventing the
  // token it needs. Every arm is written once, and entered there.
  std::vector<std::string> entry(dec.nalts);
  line("if (!kTable.holds(kTable.dec_first(", n.decision, "u), c.la.sym)) {");
  open();
  const std::string fix = concat("::cursiv::engine::ll_choice_fix<kTable>(c, ",
                                 dec.mode, "u, ", n.decision, "u)");
  if (direct) {
    open("switch (", fix, ") {");
    for (std::uint16_t i = 0; i < dec.nalts; ++i) {
      if (byArm[i].empty()) continue;
      entry[i] = name("A");
      line("case ", i, "u: goto ", entry[i], ";");
    }
    line("default: break;");
    close("}");
  } else {
    line(k, " = ", fix, ";");
  }
  if (asks)
    line(none, " = !kTable.holds(kTable.dec_first(", n.decision,
         "u), c.la.sym);");
  close("}");
  if (direct) {
    open("switch (c.la.sym) {");
  } else {
    memo.predicts = true;
    open(ended ? "switch (c.la.end == c.len ? 0xFFFFu : c.la.sym) {"
               : "switch (c.la.sym) {");
    for (std::uint16_t i = 0; i < dec.nalts; ++i)
      for (std::uint16_t t : byArm[i])
        line("case ", t, "u: ", k, " = ", i, "u; break;");
    if (asks)
      line("default: if (", k, " == 0xFFFFu) ", k, " = ", none, " ? ",
           dec.repair,
           "u : "
           "::cursiv::engine::ll_predict<kTable>(c, ",
           n.decision, "u); break;");
    else
      line("default: if (", k, " == 0xFFFFu) ", k,
           " = "
           "::cursiv::engine::ll_predict<kTable>(c, ",
           n.decision, "u); break;");
    close("}");
    open("switch (", k, ") {");
  }
  for (std::uint16_t i = 0; i < dec.nalts; ++i) {
    if (direct) {
      if (byArm[i].empty()) continue;
      std::string cases;
      for (std::uint16_t t : byArm[i]) cases += concat("case ", t, "u: ");
      if (!entry[i].empty()) cases += entry[i] + ": ";
      open(cases + "{");
    } else {
      entry[i] = name("R");
      open("case ", i, "u: ", entry[i], ": {");
    }
    // One label, one terminal: the arm knows which token it holds. Several,
    // and it knows only that it holds one.
    const std::uint16_t hand =
        direct ? (byArm[i].size() == 1 ? byArm[i][0] : kAnyToken) : kAnyToken;
    co_await arm(child_at(n, i), hand);
    line("break;");
    close("}");
  }
  // A choice no arm answers, even after the skip. One invented token is a
  // repair, a whole invented construct is not. An arm that reads the token in
  // hand, refused only after it, is entered and repaired there.
  const auto reread = [&] {
    if (direct) return;
    line("switch (::cursiv::engine::ll_reading_fix<kTable>(c, ", n.decision,
         "u)) {");
    open();
    for (std::uint16_t i = 0; i < dec.nalts; ++i)
      line("case ", i, "u: goto ", entry[i], ";");
    line("default: break;");
    close("}");
  };
  // The invented arm is entered where the switch writes it, if it does.
  const auto invent = [&] { line("goto ", entry[dec.repair], ";"); };
  if (dec.repairCost <= 1) {
    open("default: {");
    reread();
    invent();
    close("}");
  } else {
    // A choice too costly to invent still skips one token, so the loop it
    // stands in goes on. At the end of the text the arm is invented whole.
    open("default:");
    reread();
    if (dec.repairCost != kLlRepairCostless) {
      open("if (::cursiv::engine::ll_ends<kTable>(c, c.la.sym)) {");
      invent();
      close();
      open("} else {");
      line("::cursiv::engine::ll_drop<kTable>(c);");
      close("}");
    } else {
      line("::cursiv::engine::ll_drop<kTable>(c);");
    }
    line("break;");
    close();
  }
  close("}");
}

// An arm whose code outgrows `kArmBytes` and reads no record around it moves
// out of the rule's step: a function the choice calls, or, if a call in it may
// suspend, a step of its own the machine runs. Inner arms move first.
Descent<void> Emit::arm(std::uint16_t id, std::uint16_t hand) {
  const std::size_t from = size();
  const std::size_t took = taken.size();
  const std::size_t resumed = labels.size();
  co_await group(id, hand);
  const bool step = co_await may_suspend(id);
  if (size() - from < kArmBytes || regionAt.live() || foldAt.live() ||
      (step && memo.steps >= kLastStep))
    co_return;
  Arm moved{.tag = concat(inRule, "_", arms.size())};
  if (!step) {
    moved.body =
        concat("CURSIV_NOINLINE void s", moved.tag,
               "(::cursiv::engine::LlContext& c) {\n", cut_from(from), "}\n\n");
    line("s", moved.tag, "(c);");
    arms.push_back(std::move(moved));
    co_return;
  }
  moved.step = memo.steps++;
  moved.frame = frame_of(moved.tag, took);
  moved.body = step_head(moved.tag, resumed);
  moved.body += cut_from(from);
  moved.body += "  return ::cursiv::engine::kLlDone;\n}\n\n";
  taken.resize(took);
  labels.resize(resumed);
  const unsigned k = next_label();
  line("f.pc = ", k, "u;");
  line("return ", moved.step, "u;");
  line("L", k, ":;");
  arms.push_back(std::move(moved));
}

// A choice whose arms each read one terminal on a token of their own, as data:
// the token, or the repair, indexes the arms' table.
void Emit::term_choice(std::uint16_t id,
                       const std::vector<std::vector<std::uint16_t>>& byArm) {
  const LlNode& n = at(id);
  const LlDecision& dec = a.cfg.decisions[n.decision];
  const std::string k = name("k");
  peek_choice(n.decision, concat(dec.mode, "u"), true);
  line("static constexpr ::cursiv::engine::LlTermArm ", k, "a[] = {");
  for (std::uint16_t i = 0; i < dec.nalts; ++i) {
    const std::uint16_t x = child_at(n, i);
    line("    {", at(x).sym, "u, ", at(x).mode, "u, ", at(x).row, "u, ", x + 1,
         "u},");
  }
  line("};");
  line("::std::uint16_t ", k, ";");
  line(k, " = 0xFFFFu;");
  // A token no arm takes: the repair names the arm it enters, inventing the
  // token it needs, or repairs the text until an arm takes it.
  line("if (!kTable.holds(kTable.dec_first(", n.decision, "u), c.la.sym)) {");
  open();
  line(k, " = ::cursiv::engine::ll_choice_fix<kTable>(c, ", dec.mode, "u, ",
       n.decision, "u);");
  line("if (", k, " >= ", dec.nalts, "u) ", k, " = 0xFFFFu;");
  close("}");
  open("if (", k, " == 0xFFFFu) {");
  open("switch (c.la.sym) {");
  for (std::uint16_t i = 0; i < dec.nalts; ++i)
    line("case ", byArm[i][0], "u: ", k, " = ", i, "u; break;");
  // A choice no arm answers, even after the skip, as `decision` repairs it:
  // an arm of one terminal costs one invented token.
  line("default: ", k, " = ", dec.repair, "u; break;");
  close("}");
  close("}");
  line("if (", k, " != 0xFFFFu) ::cursiv::engine::ll_take_arm<kTable>(c, ", k,
       "a[", k, "]);");
}

// One turn of a loop, or with `body` the turn of a flat chain: the choice to
// take it, then what it reads, under the loop the chain stands in.
Descent<void> Emit::repetition(std::uint16_t id, std::uint16_t body) {
  const FieldScope scope(*this);
  const LlNode& n = at(id);
  const LlDecision& dec = a.cfg.decisions[n.decision];
  const bool flat = body != kNoRow;
  if (!flat && n.countedTail && counted_tail_flat(id)) {
    co_await counted_tail(id);
    co_return;
  }
  const bool nested = !flat && n.countedTail;
  if (nested) {
    ++nestedTurns;
    if (nestedTurns > kMaxNestedTurns)
      refuse_lowering(std::format(
          "rule `{}` repeats a `nest` more than {} times in a row, more than "
          "the LL parser supports -- narrow the range, or use `many` and "
          "check the count in validation",
          a.cfg.rule_name(inRule), kMaxNestedTurns));
  }
  bool held = !flat;
  if (held) held = co_await may_suspend(n.sym);
  // The turns are counted wherever a bound reads them: a floor guards the
  // choice, a ceiling ends the loop.
  const bool counts = !flat && (n.min != 0 || n.max != kEndless);
  const std::string i = local(held && counts, "unsigned", "i");
  if (!held) open("{");
  if (counts) line(held ? "" : "unsigned ", i, " = 0;");
  // The first turn's gap may be read under another configuration than the
  // gap between two turns.
  const std::uint16_t head = a.headMode[n.decision];
  const bool split = !flat && n.min == 0 && head != dec.mode;
  const bool reread = a.callerPeek[id] != 0;
  const std::uint16_t readHead = a.readHeadMode[n.decision];
  const std::uint16_t readNext = a.readMode[n.decision];
  const bool readSplit = reread && readHead != readNext && n.max > 1;
  const bool trackFirst = split || (!flat && !counts && readSplit);
  const std::string first =
      !trackFirst ? std::string{} : local(held, "bool", "first");
  if (trackFirst) line(held ? "" : "bool ", first, " = true;");
  const std::string mode =
      flat    ? concat(head, "u")
      : split ? concat("(", first, " ? ", head, "u : ", dec.mode, "u)")
              : concat(dec.mode, "u");
  if (!flat) open("for (;;) {");
  if (!flat && n.max != kEndless) line("if (", i, " == ", n.max, "u) break;");
  const bool guarded = n.min != 0;
  if (guarded) line("if (", i, " >= ", n.min, "u) {");
  if (guarded) open();
  peek_choice(n.decision, mode, !split);
  // A token no turn or exit admits does not end the loop: the skip stops at the
  // first token a turn starts on or the caller can go on from.
  line("::std::uint8_t fix;");
  line("fix = ::cursiv::engine::kLlLoopNone;");
  line("if (!kTable.holds(kTable.dec_first(", n.decision, "u), c.la.sym)) {");
  open();
  line("fix = ::cursiv::engine::ll_loop_fix<kTable>(c, ", mode, ", ",
       n.decision, "u);");
  line("if (fix == ::cursiv::engine::kLlLoopLeave) break;");
  close("}");
  line("bool repair;");
  line("repair = fix == ::cursiv::engine::kLlLoopTurn;");
  // Arm 0 takes a turn, arm 1 leaves: the sets were written in that order.
  const auto byToken = [&] {
    line("bool go;");
    line("go = false;");
    open("switch (c.la.sym) {");
    std::string cases;
    for (const unsigned t : a.laSet[dec.set].members())
      cases += concat("case ", t, "u: ");
    if (!cases.empty()) line(cases, "go = true; break;");
    line("default: break;");
    close("}");
    line("if (!go && repair) go = true;");
    line("if (!go) break;");
  };
  const auto byPrediction = [&] {
    memo.predicts = true;
    const std::string k = name("k");
    line("::std::uint16_t ", k, ";");
    line(k, " = ::cursiv::engine::ll_predict<kTable>(c, ", n.decision, "u);");
    // A prediction no arm answers ends the loop only where a rule above can go
    // on from the token; otherwise the loop turns and its body repairs.
    open("if (", k, " != 0) {");
    line("if (", k, " == ::cursiv::engine::kNoRow && !repair &&");
    line("    !::cursiv::engine::ll_loop_leaves<kTable>(c, ", n.decision,
         "u)) {");
    open();
    line("fix = ::cursiv::engine::ll_loop_fix<kTable>(c, ", mode, ", ",
         n.decision, "u);");
    line("if (fix == ::cursiv::engine::kLlLoopLeave) break;");
    line("repair = fix == ::cursiv::engine::kLlLoopTurn;");
    line(k, " = ::cursiv::engine::ll_predict<kTable>(c, ", n.decision, "u);");
    line("if (", k, " == ::cursiv::engine::kNoRow) repair = true;");
    close("}");
    line("if (", k, " != 0 && !repair) break;");
    close("}");
  };
  if (dec.how != LlPredict::single) {
    byPrediction();
  } else if (a.decEnded[n.decision] != 0) {
    open("if (c.la.end == c.len) {");
    byPrediction();
    close();
    open("} else {");
    byToken();
    close("}");
  } else {
    byToken();
  }
  if (guarded) close("}");
  if (reread) {
    const std::string readMode =
        flat || !readSplit ? concat(readHead, "u")
                           : concat("(", counts ? concat(i, " == 0") : first,
                                    " ? ", readHead, "u : ", readNext, "u)");
    line("::cursiv::engine::ll_repeat_read<kTable>(c, ", readMode, ");");
  }
  if (flat) {
    if (inStep) over_fold();
    co_await group(body, kAnyToken);
    close("}");
    co_return;
  }
  if (trackFirst) line(first, " = false;");
  const std::string at = local(held, "::cursiv::TextOffset", "at");
  line(held ? "" : "const ::cursiv::TextOffset ", at, " = c.at;");
  const std::string level =
      !levels ? std::string{} : local(held, "::cursiv::engine::IndentAt", "lv");
  if (levels) line(held ? "" : "const auto ", level, " = c.indent;");
  if (inStep) over_fold();
  co_await group(n.sym, guarded ? kNoRow : kAnyToken);
  if (nested) --nestedTurns;
  // A turn that gave up hands the text back to the loop, which takes another
  // on it. A turn that read nothing would turn for ever: a repair inside it
  // may have left the cursor where it found it.
  line("if (c.abandonDepth != ~::std::size_t{0}) break;");
  line("c.give = false;");
  line("if (c.at == ", at,
       levels ? concat(" && c.indent == ", level) : std::string{}, ") break;");
  if (counts) line("++", i, ";");
  close("}");
  if (!held) close("}");
}

// The optional tail of a counted repetition is nested options. Written flat,
// one loop reads the turns in a row and leaves at the first not taken.
bool Emit::counted_tail_flat(std::uint16_t id) const {
  for (;;) {
    const LlNode& n = at(id);
    if (!n.countedTail || n.leftFold || n.owns || n.row != kNoRow ||
        n.min != 0 || n.max != 1)
      return false;
    const LlNode& in = at(n.sym);
    if (!in.countedTail) return true;
    if (in.owns || in.row != kNoRow || plan.reaches_back(n.sym)) return false;
    id = child_at(in, 1);
  }
}

Descent<void> Emit::counted_tail(std::uint16_t id) {
  const FieldScope scope(*this);
  std::vector<std::pair<std::uint16_t, std::uint16_t>> turns;
  bool held = false;
  for (;;) {
    const std::uint16_t next = at(id).sym;
    const bool more = at(next).countedTail;
    const std::uint16_t body = more ? child_at(at(next), 0) : next;
    turns.emplace_back(id, body);
    held = co_await may_suspend(body) || held;
    if (!more) break;
    id = child_at(at(next), 1);
  }
  const std::string armed = local(held, "bool", "t");
  const Anchored regionHere(regionAt);
  if (!held) open("{");
  line(held ? "" : "bool ", armed, " = false;");
  open("for (;;) {");
  for (std::size_t k = 0; k < turns.size(); ++k) {
    co_await repetition(turns[k].first, turns[k].second);
    line("if (c.abandonDepth != ~::std::size_t{0}) break;");
    if (k == 0) line(armed, " = true;");
  }
  line("break;");
  close("}");
  line("if (", armed,
       " && c.abandonDepth == ~::std::size_t{0}) c.give = false;");
  if (!held) close("}");
}

// The token the point that read it pinned down is taken as read; anything
// else, or the token a repair entered the arm with, is matched or repaired.
void Emit::leaf(std::uint16_t id, std::uint16_t hand, std::uint16_t row) {
  const LlNode& n = at(id);
  if (hand == n.sym)
    line("if (c.la.sym == ", n.sym,
         "u) [[likely]] ::cursiv::engine::ll_consume<kTable>(c, ", row, "u, ",
         id + 1, "u); else");
  line(hand == n.sym ? "  " : "", "::cursiv::engine::ll_expect<kTable, ",
       n.mode, "u, ", n.sym, "u>(c, ", row, "u, ", id + 1, "u);");
}

Descent<void> Emit::node(std::uint16_t id, std::uint16_t hand) {
  const LlNode& n = at(id);
  switch (n.kind) {
    case LlShape::term:
      leaf(id, hand, n.row);
      co_return;
    case LlShape::endMark:
      line("::cursiv::engine::ll_end<kTable>(c, ", n.mode, "u);");
      line("::cursiv::engine::ll_flush_trivia<kTable>(c);");
      co_return;
    case LlShape::condition:
      if (a.cut[n.sym].none())
        line("::cursiv::engine::ll_condition_node<kTable>(c, ", n.mode, "u, ",
             n.sym, "u, ", id, "u);");
      co_return;
    case LlShape::implied:
      line("::cursiv::engine::ll_implied<kTable>(c, ", n.mode, "u, ", n.sym,
           "u, ", n.min, "u, ", n.row, "u, ", id + 1, "u);");
      co_return;
    case LlShape::empty:
      // Past the trivia a parent already wrote: the run's ends never decrease.
      if (n.owns)
        line(
            "c.last = ::cursiv::engine::ll_close<kTable>(c, c.tape.enter(), "
            "::std::max(c.at, c.triviaAt), kTable.stamp.make(",
            n.row, "u, 0));");
      co_return;
    case LlShape::call:
      call_site(id);
      co_return;
    case LlShape::seq:
      co_await sequence(id, hand);
      co_return;
    case LlShape::alt:
      co_await decision(id);
      co_return;
    case LlShape::rep:
      co_await repetition(id);
      co_return;
  }
}

// A precedence table, climbed: the operand, then one turn per operator binding
// at least as tight as the caller's. A join's record starts at the left
// operand. The right operand climbs one step tighter.
void Emit::climb(std::uint16_t r) {
  const LlClimb& cl = a.cfg.climbs[a.cfg.rules[r].climb];
  const std::uint16_t selectDec = a.cfg.nodes[cl.selectNode].decision;
  const bool select = a.cfg.decisions[selectDec].how != LlPredict::single ||
                      a.decEnded[selectDec] != 0;
  // After a turn on a non-grouping step only a looser operator goes on, in the
  // caller too. Without right-grouping operators the operand is always one step
  // tighter, and the frame keeps no flag.
  bool anyNon = false, anyRight = false, bodies = false, atomics = false;
  for (std::uint16_t k = 0; k < cl.opCount; ++k) {
    const LlClimbOp& op = a.cfg.climbOps[cl.opBase + k];
    anyNon = anyNon || op.assoc == Association::non;
    anyRight = anyRight || op.assoc == Association::right;
    const bool atomic = a.cfg.atomic_operator(op.body) != kNoRow;
    bodies = bodies || !atomic;
    atomics = atomics || atomic;
  }
  for (const auto& [type, n] : {std::pair{"unsigned", "least"},
                                {"::cursiv::CstBuilder::Open", "o"},
                                {"::cursiv::TextOffset", "b"},
                                {"::cursiv::NodeId", "w0"},
                                {"::cursiv::TextOffset", "before"},
                                {"unsigned", "prec"}})
    frame_field(type, n);
  if (anyRight) frame_field("bool", "right");
  frame_field("::cursiv::NodeId", "w1");
  if (anyNon) {
    frame_field("unsigned", "limit");
    frame_field("bool", "non");
  }
  // The statements, each led by a space, that state how an operator's step
  // groups, in the frame or in the locals `to` names.
  const auto grouping = [&](const LlClimbOp& op, std::string_view to = "f.") {
    std::string stated;
    if (anyRight)
      stated += concat(" ", to, "right = ", op.assoc == Association::right, ";");
    if (anyNon)
      stated += concat(" ", to, "non = ", op.assoc == Association::non, ";");
    return stated;
  };
  line("f.least = c.arg;");
  if (anyNon) line("f.limit = 255u;");
  new_search();
  const std::uint16_t m = descend(rule_mode(cl.primary));
  line("::cursiv::engine::ll_peek<kTable, ", m == kNoRow ? a.errMode : m,
       "u>(c);");
  line("::cursiv::engine::ll_flush_trivia<kTable>(c);");
  line("f.o = c.tape.enter();");
  line("f.b = c.la.begin;");
  line("f.w0 = c.last;");
  line("c.stack.push_back(", cl.atnEntry, "u, c.tape.stream().records());");
  invoke(cl.primary, "1u");
  line("::cursiv::engine::ll_return(c);");
  exits = true;
  line("if (c.give) goto done;");
  open("for (;;) {");
  line("f.before = c.at;");
  peek_choice(selectDec, concat(cl.mode, "u"), true);
  // Prediction can keep the first unfinished arm at the end of a document.
  // An infix has no operator there: consuming that zero-width EOF would
  // reset the repair budget and recursively invent another operand forever.
  line("if (c.la.sym == ::cursiv::engine::kEofSymbol) break;");
  // The operator's switch sets locals alone, so the compiler reads them from
  // a table; the frame takes them after it.
  line("unsigned prec; prec = 0;");
  if (anyRight) line("bool right; right = false;");
  if (anyNon) line("bool non; non = false;");
  const std::string invented = name("M");
  // The operator a repair invents: a terminal is inserted where the text stops
  // and the right operand is read on from there; a rule's body invents its
  // own head. What the repair does not name leaves the climb.
  const auto repair = [&](std::string_view into) {
    line(into, " = ::cursiv::engine::ll_climb_fix<kTable>(c, ", cl.mode, "u, ",
         selectDec, "u);");
    line("if (", into, " == ::cursiv::engine::kLlClimbAgain) continue;");
    open("switch (", into, ") {");
    for (std::uint16_t k = 0; k < cl.opCount; ++k) {
      const LlClimbOp& op = a.cfg.climbOps[cl.opBase + k];
      const auto leaf = a.cfg.atomic_operator(op.body);
      if (leaf == kNoRow) {
        if (!select)
          line("case ", k, "u: prec = ", op.prec, "u;", grouping(op, ""),
               " body = ", k, "u; break;");
        continue;
      }
      open("case ", k, "u:");
      line("f.prec = ", op.prec, "u;");
      if (const std::string stated = grouping(op); !stated.empty())
        line(std::string_view(stated).substr(1));
      line("if (f.prec < f.least) break;");
      join(cl.leftBase, cl.leftCount, "f.w0");
      const auto& token = at(leaf);
      line("::cursiv::engine::ll_insert_planned<kTable>(c, ", token.sym, "u, ",
           token.row, "u, ", leaf + 1, "u);");
      line("goto ", invented, ";");
      close();
    }
    line("default: break;");
    close("}");
  };
  if (!select) {
    line("::cursiv::ElementId row;");
    line("row = 0xFFFFu;");
    line("::std::uint16_t pos;");
    line("pos = 0;");
    if (bodies) {
      line("::std::uint16_t body;");
      line("body = ::cursiv::engine::kNoRow;");
    }
    open("switch (c.la.sym) {");
  } else {
    memo.predicts = true;
    line("::std::uint16_t op;");
    line("bool bad;");
    line("bad = !kTable.holds(kTable.dec_first(", selectDec, "u), c.la.sym);");
    open("if (!bad) {");
    line("op = ::cursiv::engine::ll_predict<kTable>(c, ", selectDec, "u);");
    line("if (op >= ", cl.opCount,
         "u && !::cursiv::engine::ll_climb_exits<kTable>(c, c.la.sym))");
    line("  op = ::cursiv::engine::ll_reading_fix<kTable>(c, ", selectDec,
         "u);");
    line("bad = false;");
    close("}");
    open("if (bad) {");
    repair("op");
    close("}");
    open("switch (op) {");
  }
  for (std::uint16_t k = 0; k < cl.opCount; ++k) {
    const LlClimbOp& op = a.cfg.climbOps[cl.opBase + k];
    if (select) {
      line("case ", k, "u: prec = ", op.prec, "u;", grouping(op, ""),
           " break;");
      continue;
    }
    const auto leaf = a.cfg.atomic_operator(op.body);
    if (leaf == kNoRow) {
      const LlDecision& choice = a.cfg.decisions[selectDec];
      std::string cases;
      for (const unsigned t : a.laSet[choice.set + k].members())
        cases += concat("case ", t, "u: ");
      line(cases, "prec = ", op.prec, "u;", grouping(op, ""), " body = ", k,
           "u; break;");
      continue;
    }
    // A guarded operator leaves its choice to a closure, never to one token.
    if (leaf != op.body)
      throw std::logic_error("cursiv: an LL operator switch reads a condition");
    const auto& token = at(leaf);
    line("case ", token.sym, "u:");
    line("prec = ", op.prec, "u;", grouping(op, ""), " row = ", token.row,
         "u; pos = ", leaf + 1, "u; break;");
  }
  line("default: break;");
  close("}");
  if (!select) {
    // A token neither an operator nor one a caller goes on from: the climb
    // is where an operator missing in front of it is invented.
    open("if (prec == 0) {");
    line("if (kTable.holds(kTable.dec_first(", selectDec,
         "u), c.la.sym) && "
         "::cursiv::engine::ll_climb_exits<kTable>(c, c.la.sym)) break;");
    line("::std::uint16_t fix;");
    repair("fix");
    close("}");
  }
  line("f.prec = prec;", anyRight ? " f.right = right;" : "",
       anyNon ? " f.non = non;" : "");
  line(anyNon
           ? "if (f.prec == 0 || f.prec < f.least || f.prec > f.limit) break;"
           : "if (f.prec == 0 || f.prec < f.least) break;");
  join(cl.leftBase, cl.leftCount, "f.w0");
  if (!select && !bodies) {
    line("::cursiv::engine::ll_consume<kTable>(c, row, pos);");
  } else {
    open(select ? "switch (op) {" : "switch (body) {");
    for (std::uint16_t k = 0; k < cl.opCount; ++k) {
      const auto& op = a.cfg.climbOps[cl.opBase + k];
      const auto leaf = a.cfg.atomic_operator(op.body);
      if (!select && leaf != kNoRow) continue;
      open("case ", k, "u: {");
      if (leaf != kNoRow) {
        // Prediction chooses an operator arm but does not replace the token
        // held by the wider climb alphabet. Its terminal position reads the
        // selected spelling again before consuming the operator's own span.
        const auto& token = at(leaf);
        line("::cursiv::engine::ll_expect<kTable, ", token.mode, "u, ",
             token.sym, "u>(c, ", token.row, "u, ", leaf + 1, "u);");
      } else {
        descend(group(op.body, kAnyToken));
      }
      line("break;");
      close("}");
    }
    line(select ? "default: break;"
                : "default: ::cursiv::engine::ll_consume<kTable>(c, row, pos); "
                  "break;");
    close("}");
  }
  line("if (c.give) break;");
  if (atomics) line(invented, ":;");
  line("f.w1 = c.last;");
  invoke(r, anyRight ? "f.right ? f.prec : f.prec + 1" : "f.prec + 1");
  if (anyNon) line("f.limit = f.non ? f.prec - 1u : f.prec;");
  join(cl.rightBase, cl.rightCount, "f.w1");
  line(
      "c.last = ::cursiv::engine::ll_close<kTable>(c, f.o, f.b, "
      "kTable.stamp.make(",
      cl.node,
      "u, "
      "0));");
  line("if (c.give || c.at == f.before) break;");
  close("}");
}

std::string Emit::frame_of(std::string_view tag, std::size_t from) const {
  std::vector<std::size_t> own(
      taken.begin() + static_cast<std::ptrdiff_t>(from), taken.end());
  std::ranges::sort(own);
  own.erase(std::ranges::unique(own).begin(), own.end());
  std::string s = concat("struct F", tag, " {\n  ::std::uint16_t pc;\n");
  for (const std::size_t k : own)
    s += concat("  ", fields[k].first, " ", fields[k].second, ";\n");
  return s + "};\n";
}

std::string Emit::resume_switch(std::size_t resumed) const {
  std::string s = "  switch (f.pc) {\n";
  for (std::size_t i = resumed; i < labels.size(); ++i)
    s += concat("    case ", labels[i], "u: goto L", labels[i], ";\n");
  return s + "    default: break;\n  }\n";
}

std::string Emit::step_head(std::string_view tag, std::size_t resumed) const {
  return concat("::std::uint16_t s", tag,
                "(::cursiv::engine::LlContext& c, void* frame) {\n"
                "  auto& f = *::std::launder(static_cast<F",
                tag, "*>(frame));\n", resume_switch(resumed));
}

// One rule as a step: its frame holds what outlives a call, and the step jumps
// back to the label a call resumes at. A plain rule is a function with no
// frame. A rule entered after its caller gave up opens nothing.
void Emit::rule(std::uint16_t r) {
  const LlRuleInfo& u = a.cfg.rules[r];
  open();
  inRule = r;
  if (u.climb != kNoRow)
    climb(r);
  else if (u.body != kNoRow)
    descend(group(u.body));
  std::string body = take();
  close();
  if (plain(r)) {
    if (resumes != 0 || !fields.empty() || exits)
      throw std::logic_error("cursiv: a plain LL rule resumes");
    frame.clear();
    line("void s", r, "(::cursiv::engine::LlContext& c) {");
    line("  if (c.give) {\n    c.repaired.mark();\n    return;\n  }");
    write(body);
    line("}\n");
    return;
  }
  frame = frame_of(std::to_string(r), 0);
  write(step_head(std::to_string(r), 0));
  line(
      "  if (c.give) {\n    c.repaired.mark();\n"
      "    return ::cursiv::engine::kLlDone;\n  }");
  write(body);
  if (exits) line("done:");
  line("  return ::cursiv::engine::kLlDone;\n}\n");
}

