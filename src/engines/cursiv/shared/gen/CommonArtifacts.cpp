// The grammar's own text and rule data: what a language answers when asked
// for its grammar. `wrapped` is the text folded for review, as `GRAMMAR.txt`
// holds it.
std::string emit_grammar_source(std::string_view ns, const GrammarDump& dump,
                                std::string_view wrapped) {
  TextBuilder out;
  out.write(R"(// generated by cursiv gen -- do not edit
#pragma once

#include <string_view>
#include "cursiv/grammar/GrammarSourceData.hpp"

namespace )",
            ns, R"( {

)");
  const auto text = [&](std::string_view name, std::string_view value) {
    out.line("inline constexpr ::std::string_view ", name, "{");
    std::size_t at = 0;
    for (;;) {
      const auto nl = value.find('\n', at);
      const auto end = nl == std::string_view::npos ? value.size() : nl + 1;
      out.line("    ", c_literal(value.substr(at, end - at)));
      if (nl == std::string_view::npos) break;
      at = end;
    }
    out.line("    , ", value.size(), "u};\n");
  };
  text("kGrammarText", dump.text);
  text("kGrammarWrappedText", wrapped);
  out.line("inline constexpr ::std::size_t kGrammarDependencies[] = {");
  for (const auto& rule : dump.rules)
    for (const auto target : rule.dependencies) out.line("    ", target, "u,");
  out.line("    0u,\n};");
  out.line(
      "inline constexpr ::cursiv::detail::GrammarSourceRule kGrammarRules[] = "
      "{");
  std::size_t at = 0;
  for (const auto& rule : dump.rules) {
    out.line("    {", c_literal(rule.name), ", kGrammarText.substr(",
             rule.begin, "u, ", rule.size,
             "u), "
             "{kGrammarDependencies + ",
             at, "u, ", rule.dependencies.size(), "u}},");
    at += rule.dependencies.size();
  }
  out.line(
      "};\ninline constexpr ::cursiv::detail::GrammarSourceData "
      "kGrammarSource{\n"
      "    kGrammarWrappedText, kGrammarRules};");
  out.line("\n}  // namespace ", ns);
  return out.take();
}

// The module the generator owns: what derives from the grammar, installed on
// the services a language holds. The module the author writes adds its own
// over it. Only the parser it installs names an engine.
std::string emit_module_decl(std::string_view ns,
                             const LanguageIdentity& lang) {
  return concat(R"(// generated by cursiv gen -- do not edit
#pragma once

#include <memory>
#include <string_view>

#include "cursiv/grammar/GrammarSource.hpp"
#include "cursiv/parser/Parser.hpp"
#include "cursiv/services/CoreServices.hpp"
#include "cursiv/syntax-tree/AstReflection.hpp"

namespace )",
                ns, R"( {

inline constexpr ::std::string_view kLanguageId = )",
                c_literal(lang.id), R"(;

::std::unique_ptr<::cursiv::Parser> create_parser();
::std::unique_ptr<::cursiv::AstReflection> create_ast_reflection();
::std::unique_ptr<const ::cursiv::GrammarSource> create_grammar_source();
void install_generated_module(::cursiv::CoreServices& services);

}  // namespace )",
                ns, R"(
)");
}

std::string emit_module(std::string_view ns, const LanguageIdentity& lang,
                        std::string_view header, std::string_view parser) {
  TextBuilder out;
  out.write(R"(// generated by cursiv gen -- do not edit
#include "Module.hpp"

#include <memory>
#include <string>

#include "AstReflection.hpp"
#include "Grammar.hpp"
#include "GrammarSource.hpp"
#include "Parser.hpp"
#include "Table.hpp"
#include "cursiv/grammar/DefaultGrammarSource.hpp"
#include ")",
            header, R"("
#include "cursiv/syntax-tree/DefaultAstReflection.hpp"

namespace )",
            ns, R"( {

::std::unique_ptr<::cursiv::Parser> create_parser() {
  return ::std::make_unique<::cursiv::engine::)",
            parser, R"(<kTable>>(
      kGrammarMetaData, kAstActions, kDrive);
}

::std::unique_ptr<::cursiv::AstReflection> create_ast_reflection() {
  return ::std::make_unique<::cursiv::DefaultAstReflection>(
      kAstMetaData);
}

::std::unique_ptr<const ::cursiv::GrammarSource> create_grammar_source() {
  return ::std::make_unique<::cursiv::DefaultGrammarSource>(
      kGrammarSource);
}

void install_generated_module(::cursiv::CoreServices& services) {
)");
  const auto list = [](const std::vector<std::string>& v) {
    return concat("{", joined(v, ", ", c_literal), "}");
  };
  if (!lang.id.empty())
    out.write(R"(  if (services.languageMetaData.languageId.empty())
    services.languageMetaData.languageId = kLanguageId;
)");
  // Named or not at all: a grammar that declares none leaves whatever the
  // container already knew, as the two fields either side of it do.
  if (!lang.extensions.empty())
    out.line("  services.languageMetaData.fileExtensions = ",
             list(lang.extensions), ";");
  if (!lang.fileNames.empty())
    out.line("  services.languageMetaData.fileNames = ", list(lang.fileNames),
             ";");
  out.write(R"(  services.parser = create_parser();
  services.astReflection = create_ast_reflection();
  services.grammarSource = create_grammar_source();
}

}  // namespace )",
            ns, R"(
)");
  return out.take();
}

