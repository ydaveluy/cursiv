// The grammar's own text and rule data: what a language answers when asked
// for its grammar.
std::string emit_grammar_source(std::string_view ns, const GrammarDump& dump) {
  std::string out = std::format(R"(// generated by cursiv gen -- do not edit
#pragma once

#include <string_view>
#include "cursiv/core/grammar/GrammarSourceData.hpp"

namespace {} {{

)",
                                ns);
  const auto text = [&](std::string_view name, std::string_view value) {
    out += std::format("inline constexpr ::std::string_view {}{{\n", name);
    std::size_t at = 0;
    for (;;) {
      const auto nl = value.find('\n', at);
      const auto end = nl == std::string_view::npos ? value.size() : nl + 1;
      out += "    " + c_literal(value.substr(at, end - at)) + "\n";
      if (nl == std::string_view::npos) break;
      at = end;
    }
    out += std::format("    , {}u}};\n\n", value.size());
  };
  text("kGrammarText", dump.text);
  text("kGrammarWrappedText", dump_wrapped(dump.text));
  out += "inline constexpr ::std::size_t kGrammarDependencies[] = {\n";
  for (const auto& rule : dump.rules)
    for (const auto target : rule.dependencies)
      out += std::format("    {}u,\n", target);
  out += "    0u,\n};\n";
  out += "inline constexpr ::cursiv::GrammarSourceRule kGrammarRules[] = {\n";
  std::size_t at = 0;
  for (const auto& rule : dump.rules) {
    out += std::format(
        "    {{{}, kGrammarText.substr({}u, {}u), "
        "{{kGrammarDependencies + {}u, {}u}}}},\n",
        c_literal(rule.name), rule.begin, rule.size, at,
        rule.dependencies.size());
    at += rule.dependencies.size();
  }
  out +=
      "};\ninline constexpr ::cursiv::GrammarSourceData kGrammarSource{\n"
      "    kGrammarWrappedText, kGrammarRules};\n";
  out += std::format("\n}}  // namespace {}\n", ns);
  return out;
}

// The module the generator owns: what derives from the grammar, installed on
// the services a language holds. The module the author writes adds its own
// over it. Only the parser it installs names an engine.
std::string emit_module_decl(std::string_view ns,
                             const LanguageIdentity& lang) {
  return std::format(R"(// generated by cursiv gen -- do not edit
#pragma once

#include <memory>
#include <string_view>

#include "cursiv/core/grammar/GrammarSource.hpp"
#include "cursiv/core/parser/Parser.hpp"
#include "cursiv/core/services/CoreServices.hpp"
#include "cursiv/core/syntax-tree/AstReflection.hpp"

namespace {0} {{

inline constexpr ::std::string_view kLanguageId = {1};

::std::unique_ptr<::cursiv::Parser> create_parser();
::std::unique_ptr<::cursiv::AstReflection> create_ast_reflection();
::std::unique_ptr<const ::cursiv::GrammarSource> create_grammar_source();
void install_generated_module(::cursiv::CoreServices& services);

}}  // namespace {0}
)",
                     ns, c_literal(lang.id));
}

std::string emit_module(std::string_view ns, const LanguageIdentity& lang,
                        std::string_view header, std::string_view parser) {
  std::string out = std::format(R"(// generated by cursiv gen -- do not edit
#include "Module.hpp"

#include <memory>
#include <string>

#include "AstReflection.hpp"
#include "Grammar.hpp"
#include "GrammarSource.hpp"
#include "Parser.hpp"
#include "Table.hpp"
#include "cursiv/core/grammar/DefaultGrammarSource.hpp"
#include "{1}"
#include "cursiv/core/syntax-tree/DefaultAstReflection.hpp"

namespace {0} {{

::std::unique_ptr<::cursiv::Parser> create_parser() {{
  return ::std::make_unique<::cursiv::{2}<kTable>>(
      kGrammarMetaData, kAstActions, kDrive);
}}

::std::unique_ptr<::cursiv::AstReflection> create_ast_reflection() {{
  return ::std::make_unique<::cursiv::DefaultAstReflection>(
      kAstMetaData);
}}

::std::unique_ptr<const ::cursiv::GrammarSource> create_grammar_source() {{
  return ::std::make_unique<::cursiv::DefaultGrammarSource>(
      kGrammarSource);
}}

void install_generated_module(::cursiv::CoreServices& services) {{
)",
                                ns, header, parser);
  const auto list = [](const std::vector<std::string>& v) {
    return "{" + join(v, ", ", c_literal) + "}";
  };
  if (!lang.id.empty())
    out += R"(  if (services.languageMetaData.languageId.empty())
    services.languageMetaData.languageId = kLanguageId;
)";
  // Named or not at all: a grammar that declares none leaves whatever the
  // container already knew, as the two fields either side of it do.
  if (!lang.extensions.empty())
    out += std::format("  services.languageMetaData.fileExtensions = {};\n",
                       list(lang.extensions));
  if (!lang.fileNames.empty())
    out += std::format("  services.languageMetaData.fileNames = {};\n",
                       list(lang.fileNames));
  out += std::format(R"(  services.parser = create_parser();
  services.astReflection = create_ast_reflection();
  services.grammarSource = create_grammar_source();
}}

}}  // namespace {}
)",
                     ns);
  return out;
}

